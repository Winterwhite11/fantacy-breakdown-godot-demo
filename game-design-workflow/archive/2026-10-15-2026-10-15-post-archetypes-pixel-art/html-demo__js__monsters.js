  /** 把字符位图转成多色 SVG（同行同色合并成一条 rect，压缩体积） */
  function bitmapToSvg(rows) {
    const parts = [];
    for (let y = 0; y < rows.length; y++) {
      const row = rows[y];
      let x = 0;
      while (x < row.length) {
        const ch = row[x];
        if (ch === "." || !PAL[ch]) { x++; continue; }
        let x2 = x + 1;
        while (x2 < row.length && row[x2] === ch) x2++;
        parts.push(`<rect x="${x}" y="${y}" width="${x2 - x}" height="1" fill="${PAL[ch]}"/>`);
        x = x2;
      }
    }
    return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${GRID} ${GRID}" ` +
      `shape-rendering="crispEdges">${parts.join("")}</svg>`;
  }

  function svgToDataUri(svg) {
    return `url("data:image/svg+xml,${encodeURIComponent(svg)}")`;
  }

  const CLS = "fb-monster";

  /**
   * 注入样式：每个怪物一条 `--monster-<id>` 变量 + 一个共享类。
   * 与 pieces.js 的 mask 方案一致：立绘是 SVG 遮罩，颜色由 CSS 控制，
   * 这样同一个位图可以在不同状态（受击/死亡）下换色。
   */
  function applyTo(doc = root?.document) {
    if (!doc) return 0;
    const target = doc.head || doc.documentElement;
    if (!target) return 0;
    let css = "";
    for (const [id, rows] of Object.entries(BITMAPS)) {
      const uri = svgToDataUri(bitmapToSvg(rows));
      const color = GLOW[id] || "#8fa6c4";
      css += `.--monster-${id}{--fb-monster-mask:${uri};--fb-monster-glow:${color};}\n`;
    }
    const style = doc.createElement("style");
    style.setAttribute("data-fb-monsters", "1");
    style.textContent = css;
    target.appendChild(style);
    return Object.keys(BITMAPS).length;
  }

  /** 单位名 → 位图 id（找不到时返回 null，由调用方回退首字徽记） */
  function artFor(name) {
    if (!name) return null;
    if (NAME_TO_ART[name]) return NAME_TO_ART[name];
    // 模糊匹配：包含关系（如「大史莱姆」优先于「史莱姆」）
    const keys = Object.keys(NAME_TO_ART).sort((a, b) => b.length - a.length);
    for (const k of keys) if (String(name).includes(k)) return NAME_TO_ART[k];
    return null;
  }

  /** 生成立绘元素的 class（含回退） */
  function classFor(name) {
    const art = artFor(name);
    return art ? `${CLS} --monster-${art}` : `${CLS} ${CLS}-fallback`;
  }

  root.FBMonsters = {
    BITMAPS, PAL, GLOW, NAME_TO_ART, GRID, CLS,
    bitmapToSvg, svgToDataUri, applyTo, artFor, classFor,
  };
